"""Writes sw.js with the list of every app file and a version based on their contents.
Run this after changing any file, before uploading to GitHub (it is already run for this release)."""
import hashlib, os
ROOT = os.path.dirname(os.path.abspath(__file__))
SKIP = {'sw.js', 'make_sw.py', 'README.md', '.nojekyll', 'THIRD_PARTY_LICENSES.txt'}
files, h = [], hashlib.sha1()
for d, _, fs in os.walk(ROOT):
    if '/.git' in d: continue
    for f in sorted(fs):
        rel = os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/')
        if f in SKIP or rel.startswith('.') or f.startswith('LICENSE'): continue
        files.append(rel); h.update(rel.encode()); h.update(open(os.path.join(d, f), 'rb').read())
files.sort()
ver = h.hexdigest()[:10]
listing = ',\n  '.join("'./%s'" % f for f in files)
open(os.path.join(ROOT, 'sw.js'), 'w').write("""/* Offline support: keeps a copy of every app file on this PC. Generated by make_sw.py - version %s */
const CACHE = 'cfs-stock-desk-%s';
const FILES = ['./',
  %s];
self.addEventListener('install', e => {
  // cache: 'reload' = always take the files from GitHub, never an older copy from the browser's own cache
  // v17.1: a new version waits until the user clicks "New version – click to refresh" (no half-updated screens)
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(u, {cache: 'reload'})))));
});
self.addEventListener('message', e => { if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting(); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('cfs-stock-desk-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
/* Program files (page, .js, .css): newest from GitHub when online, saved copy when offline.
   Big fixed libraries (OCR, PDF engine, language data): saved copy first - they never change between versions. */
const BIG = /(\\.wasm|\\.gz|\\.min\\.js|pdfium\\.js|\\.png)$/;
self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  const fromCache = () => caches.match(req, {ignoreSearch: true});
  const save = res => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req.mode === 'navigate' ? './' : req, copy)); } return res; };
  if (BIG.test(url.pathname)) {
    e.respondWith(fromCache().then(hit => hit || fetch(req).then(save)));
    return;
  }
  e.respondWith(fetch(req.mode === 'navigate' ? req : new Request(req, {cache: 'no-cache'})).then(save)
    .catch(() => fromCache().then(hit => hit || caches.match('./'))));
});
""" % (ver, ver, listing))
print('sw.js written: version', ver, '-', len(files), 'files')
